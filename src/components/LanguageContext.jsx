const LanguageContext = createContext();

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('acc_lang') || 'th');

  useEffect(() => {
    localStorage.setItem('acc_lang', lang);
  }, [lang]);

  const t = (key, params) => {
    let text = translations[lang]?.[key] || translations['th']?.[key] || key;
    if (params) {
      Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, v);
      });
    }
    return text;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    // Fallback when context is not available (e.g. during HMR)
    const fallbackT = (key) => translations['th']?.[key] || key;
    return { lang: 'th', setLang: () => {}, t: fallbackT };
  }
  return ctx;
}